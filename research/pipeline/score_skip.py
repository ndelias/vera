"""Study 08: score what Triage (or the rules) would let reviewers skip.

    python3 research/pipeline/score_skip.py <split> [system ...]

For each system (a batch under research/data/batches/<system>/) and for the
rules baseline: the share of changed lines skipped, and the share of spots
that mattered that fell in skipped hunks, pooled over pull requests, with
95% bootstrap intervals (resampling pull requests). See
studies/08-skip/DESIGN.md. Prints counts only.
"""

import json
import random
import re
import sys
from pathlib import Path

from db import ROOT, connect

BATCHES = ROOT / "data" / "batches"
OUT = ROOT / "studies" / "08-skip"
SEED = 20261125
ENGINEERS_ONLY = {"docs", "copy"}  # mirrors clearedFor() in packages/agents/src/triage.ts
DRAWS = 2000

LOCKFILES = {"package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock", "uv.lock", "cargo.lock",
             "go.sum", "gemfile.lock", "composer.lock", "pipfile.lock", "bun.lockb", "bun.lock"}
DOCS = (".md", ".mdx", ".txt", ".rst")
GENERATED_MARK = re.compile(r"@generated|DO NOT EDIT|Code generated|autogenerated|auto-generated", re.I)
IMPORT = re.compile(r"^(import\s|from\s+\S+\s+import\s|export\s+\*\s+from\s|export\s+\{[^}]*\}\s+from\s|\}\s*from\s+['\"]|"
                    r"const\s+\w+\s*=\s*require\(|use\s+[\w:]+;$)")


def cid(pr: str) -> str:
    return re.sub(r"[^A-Za-z0-9_-]", "_", pr)[:64]


def changed(text: str) -> tuple[list[str], list[str]]:
    plus, minus = [], []
    for line in text.split("\n")[1:]:
        if line.startswith("+"):
            plus.append(line[1:])
        elif line.startswith("-"):
            minus.append(line[1:])
    return plus, minus


def rule_skip(path: str, text: str) -> bool:
    p = path.lower()
    name = p.rsplit("/", 1)[-1]
    if name in LOCKFILES or p.endswith(".snap") or "/__snapshots__/" in f"/{p}":
        return True
    if any(seg in ("generated", "__generated__") for seg in p.split("/")[:-1]) or GENERATED_MARK.search(text):
        return True
    if p.endswith((".min.js", ".min.css")) or p.endswith(DOCS):
        return True
    plus, minus = changed(text)
    squash = lambda ls: sorted("".join(l.split()) for l in ls if l.strip())
    if squash(plus) == squash(minus):
        return True  # whitespace only
    lines = [l.strip() for l in plus + minus if l.strip()]
    return bool(lines) and all(IMPORT.match(l) for l in lines)


def rows(conn, split: str):
    prs = [r[0] for r in conn.execute("SELECT id FROM sk_prs WHERE split = ? ORDER BY id", (split,))]
    hunks = {}
    for pr, n, path, added, deleted, text in conn.execute(
            "SELECT h.pr, h.n, h.path, h.added, h.deleted, h.text FROM sk_hunks h JOIN sk_prs p ON p.id = h.pr WHERE p.split = ?", (split,)):
        hunks.setdefault(pr, {})[n] = (path, added + deleted, text)
    spots = {}
    for pr, hunk in conn.execute(
            "SELECT s.pr, s.hunk FROM sk_spots s JOIN sk_prs p ON p.id = s.pr WHERE p.split = ? AND s.mattered = 1 AND s.hunk IS NOT NULL", (split,)):
        spots.setdefault(pr, []).append(hunk)
    return prs, hunks, spots


def per_pr(prs, hunks, spots, skipped: dict[str, set[int]]):
    """(changed lines, skipped lines, spots that mattered, of them skipped) per PR."""
    out = []
    for pr in prs:
        hs, sk = hunks.get(pr, {}), skipped.get(pr, set())
        lines = sum(n for _, n, _ in hs.values())
        out.append((lines, sum(hs[i][1] for i in sk if i in hs), len(spots.get(pr, [])), sum(1 for h in spots.get(pr, []) if h in sk)))
    return out


def summary(table) -> dict:
    def ratios(t):
        L, S, M, X = (sum(r[i] for r in t) for i in range(4))
        return S / L if L else 0.0, X / M if M else 0.0
    saved, missed = ratios(table)
    rng = random.Random(SEED)
    draws = [ratios([rng.choice(table) for _ in table]) for _ in range(DRAWS)]
    ci = lambda xs: [round(sorted(xs)[int(0.025 * DRAWS)], 4), round(sorted(xs)[int(0.975 * DRAWS) - 1], 4)]
    return {
        "prs": len(table),
        "lines": sum(r[0] for r in table), "lines_skipped": sum(r[1] for r in table),
        "spots": sum(r[2] for r in table), "spots_skipped": sum(r[3] for r in table),
        "saved": round(saved, 4), "saved_ci": ci([d[0] for d in draws]),
        "missed": round(missed, 4), "missed_ci": ci([d[1] for d in draws]),
    }


NEAR = 3  # as in collect_skip_prs.py


def changed_lines(text: str) -> list[int]:
    """New-side line numbers of a hunk's changes; a deletion counts at the line it sits before."""
    m = re.match(r"@@ -\d+(?:,\d+)? \+(\d+)", text)
    n, out = int(m[1]) if m else 0, []
    for line in text.split("\n")[1:]:
        if line.startswith("+"):
            out.append(n)
            n += 1
        elif line.startswith("-"):
            out.append(n)
        elif not line.startswith("\\"):
            n += 1
    return out


def brief_scores(conn, split: str, system: str) -> dict:
    """Verify: of the spots that mattered, the share inside the brief's places (± NEAR
    lines, same file), and the share of changed lines inside those places."""
    def span(lines: str):
        nums = [int(x) for x in re.findall(r"\d+", lines or "")]
        return (min(nums[0], nums[1 if len(nums) > 1 else 0]), max(nums[0], nums[1 if len(nums) > 1 else 0])) if nums else None
    table, failed = [], 0
    for (pr,) in conn.execute("SELECT id FROM sk_prs WHERE split = ? ORDER BY id", (split,)):
        f = BATCHES / system / f"{cid(pr)}.json"
        out = json.loads(f.read_text()) if f.exists() else None
        if not f.exists():
            continue
        places = [(pl["file"], span(pl.get("lines", ""))) for pl in ((out or {}).get("places") or [])]
        places = [(fi, sp) for fi, sp in places if sp]
        failed += not out
        hunks = {n: (path, text) for n, path, text in conn.execute("SELECT n, path, text FROM sk_hunks WHERE pr = ?", (pr,))}
        total = inside = 0
        for path, text in hunks.values():
            for ln in changed_lines(text):
                total += 1
                inside += any(fi == path and sp[0] <= ln <= sp[1] for fi, sp in places)
        spots = caught = 0
        for path, side, first, last, hunk in conn.execute(
                "SELECT path, side, first, last, hunk FROM sk_spots WHERE pr = ? AND mattered = 1 AND hunk IS NOT NULL", (pr,)):
            if side != "RIGHT":
                h = re.match(r"@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))?", hunks[hunk][1])
                first, last = int(h[1]), int(h[1]) + max(int(h[2] or 1), 1) - 1
            spots += 1
            caught += any(fi == path and sp[0] <= last + NEAR and first - NEAR <= sp[1] for fi, sp in places)
        table.append((total, inside, spots, caught))
    sm = summary([(t, i, sp, c) for t, i, sp, c in table])
    return {"prs": sm["prs"], "lines": sm["lines"], "lines_in_verify": sm["lines_skipped"], "verify_share": sm["saved"], "verify_share_ci": sm["saved_ci"],
            "spots": sm["spots"], "spots_caught": sm["spots_skipped"], "caught": sm["missed"], "caught_ci": sm["missed_ci"], "failed": failed}


def main() -> None:
    if sys.argv[1] == "--brief":
        split, system = sys.argv[2], sys.argv[3]
        out = {"split": split, system: brief_scores(connect(), split, system)}
        print(json.dumps(out, indent=2))
        (OUT / f"scores-{split}-{system}.json").write_text(json.dumps(out, indent=2) + "\n")
        return
    split, systems = sys.argv[1], sys.argv[2:]
    conn = connect()
    prs, hunks, spots = rows(conn, split)
    results = {"split": split}
    rules = {pr: {n for n, (path, _, text) in hs.items() if rule_skip(path, text)} for pr, hs in hunks.items()}
    results["rules"] = summary(per_pr(prs, hunks, spots, rules))
    for system in systems:
        # PRs the system wasn't run on are left out (and counted); an unusable
        # answer skips nothing, so a person reads all of it.
        ran = [pr for pr in prs if (BATCHES / system / f"{cid(pr)}.json").exists()]
        skipped, failed = {}, 0
        for pr in ran:
            out = json.loads((BATCHES / system / f"{cid(pr)}.json").read_text())
            if not out or not isinstance(out.get("skip"), list):
                failed += 1
                continue
            # Scored for any reader (Nahuel's call, 25 Nov 2026): docs and wording are
            # cleared for engineers only, and we can't tell which reviewer was which.
            skipped[pr] = {s["hunk"] for s in out["skip"] if isinstance(s.get("hunk"), int) and s.get("reason") not in ENGINEERS_ONLY}
        results[system] = summary(per_pr(ran, hunks, spots, skipped)) | {"failed": failed, "not_run": len(prs) - len(ran)}
        results[f"rules on the same {len(ran)}"] = summary(per_pr(ran, hunks, spots, rules))
        reasons = {}
        for pr in prs:
            f = BATCHES / system / f"{cid(pr)}.json"
            for s in (json.loads(f.read_text()) or {}).get("skip", []) if f.exists() else []:
                reasons[s.get("reason")] = reasons.get(s.get("reason"), 0) + 1
        results[system]["reasons"] = dict(sorted(reasons.items(), key=lambda kv: -kv[1]))
    print(json.dumps(results, indent=2))
    if systems:
        OUT.mkdir(parents=True, exist_ok=True)
        (OUT / f"scores-{split}-{'-'.join(systems)}.json").write_text(json.dumps(results, indent=2) + "\n")


if __name__ == "__main__":
    main()
